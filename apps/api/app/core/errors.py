def _extract_request_id(request: Request) -> str:
    """Safely extract request ID from state or header."""
    req_id = getattr(request.state, "request_id", None)
    if isinstance(req_id, str) and req_id:
        return req_id
    header_val = request.headers.get("X-Request-ID")
    if header_val:
        return header_val
    return str(uuid.uuid4())


async def app_exception_handler(request: Request, exc: AppException) -> JSONResponse:
    """Handle custom application exceptions."""
    request_id = _extract_request_id(request)
    problem = ProblemDetail(
        type=exc.type_uri,
        title=exc.title,
        status=exc.status_code,
        detail=exc.detail,
        instance=str(request.url.path),
        request_id=request_id,
        invalid_params=exc.invalid_params,
    )
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
        headers={"X-Request-ID": request_id},
    )


async def http_exception_handler(request: Request, exc: HTTPException) -> JSONResponse:
    """Handle standard FastAPI/Starlette HTTPExceptions with RFC 7807 format."""
    request_id = _extract_request_id(request)
    title = "HTTP Error"
    if exc.status_code == status.HTTP_404_NOT_FOUND:
        title = "Not Found"
    elif exc.status_code == status.HTTP_401_UNAUTHORIZED:
        title = "Unauthorized"
    elif exc.status_code == status.HTTP_403_FORBIDDEN:
        title = "Forbidden"
    elif exc.status_code == status.HTTP_429_TOO_MANY_REQUESTS:
        title = "Rate Limit Exceeded"

    problem = ProblemDetail(
        type="about:blank",
        title=title,
        status=exc.status_code,
        detail=str(exc.detail),
        instance=str(request.url.path),
        request_id=request_id,
    )
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
        headers={"X-Request-ID": request_id},
    )


async def validation_exception_handler(
    request: Request,
    exc: RequestValidationError,
) -> JSONResponse:
    """Handle Pydantic request validation errors."""
    request_id = _extract_request_id(request)
    invalid_params: list[InvalidParam] = []

    for err in exc.errors():
        loc = ".".join(str(part) for part in err.get("loc", []))
        msg = err.get("msg", "Invalid parameter")
        invalid_params.append(InvalidParam(name=loc, reason=msg))

    http_422 = getattr(
        status, "HTTP_422_UNPROCESSABLE_CONTENT", status.HTTP_422_UNPROCESSABLE_ENTITY
    )
    problem = ProblemDetail(
        type="urn:bodhai:error:validation-failed",
        title="Unprocessable Content",
        status=http_422,
        detail="One or more request parameters failed validation.",
        instance=str(request.url.path),
        request_id=request_id,
        invalid_params=invalid_params,
    )
    return JSONResponse(
        status_code=http_422,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
        headers={"X-Request-ID": request_id},
    )


async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Handle unhandled server exceptions (500 Internal Server Error)."""
    request_id = _extract_request_id(request)
    logger.exception("Unhandled server exception", error=str(exc), path=str(request.url.path))

    problem = ProblemDetail(
        type="urn:bodhai:error:internal-server-error",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An unexpected error occurred. Please contact support with the request ID.",
        instance=str(request.url.path),
        request_id=request_id,
    )
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_JSON_MEDIA_TYPE,
        headers={"X-Request-ID": request_id},
    )


def register_error_handlers(app: FastAPI) -> None:
    """Register all RFC 7807 error handlers on the FastAPI application instance."""
    app.add_exception_handler(AppException, cast(Any, app_exception_handler))
    app.add_exception_handler(HTTPException, cast(Any, http_exception_handler))
    app.add_exception_handler(RequestValidationError, cast(Any, validation_exception_handler))
    app.add_exception_handler(Exception, unhandled_exception_handler)
